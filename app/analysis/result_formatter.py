"""
Deterministic result formatting for AI Data Analyst.

Formats database results directly without allowing
the LLM to modify authoritative numeric values.
"""

from decimal import Decimal
from typing import Any


def format_value(value: Any) -> str:
    """
    Format a single database value for display.
    """

    if isinstance(value, Decimal):
        return f"{value:,.2f}"

    if isinstance(value, float):
        return f"{value:,.2f}"

    if isinstance(value, int):
        return f"{value:,}"

    return str(value)


def format_tabular_result(
    columns: list[str],
    rows: list[Any],
) -> str:
    """
    Convert database rows into a deterministic
    human-readable answer.

    Numeric values come directly from the database
    result and are never generated by the LLM.
    """

    if not rows:
        return "No matching data was found."

    formatted_rows = []

    for row in rows:

        parts = []

        for column, value in zip(
            columns,
            row,
        ):
            parts.append(
                f"{column}: {format_value(value)}"
            )

        formatted_rows.append(
            " | ".join(parts)
        )

    return "\n".join(
        formatted_rows
    )
