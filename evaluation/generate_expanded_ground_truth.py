def main():
    print("=" * 70)
    print("GENERATING EXPANDED GROUND TRUTH")
    print("=" * 70)

    generated_questions = []

    for question_data in QUESTIONS:

        question_id = question_data["id"]
        question = question_data["question"]
        sql = question_data["sql"]

        print(
            f"\n[{question_id}] {question}"
        )

        columns, rows = execute_query(sql)

        generated_questions.append(
            {
                "id": question_id,
                "question": question,
                "expected_columns": columns,
                "expected_rows": [
                    list(row)
                    for row in rows
                ],
            }
        )

        print(
            f"Columns: {columns}"
        )

        print(
            f"Rows: {len(rows)}"
        )

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            generated_questions,
            file,
            indent=4,
            default=float,
        )

    print("\n" + "=" * 70)
    print("EXPANDED GROUND TRUTH GENERATED")
    print("=" * 70)

    print(
        f"Questions: {len(generated_questions)}"
    )

    print(
        f"Output: {OUTPUT_PATH}"
    )


if __name__ == "__main__":
    main()
